'use strict';
const { app, BrowserWindow } = require('electron');
const path = require('path');
app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 1300, height: 800, webPreferences: { preload: path.join(__dirname, '..', 'src', 'main', 'preload.js'), contextIsolation: true } });
  const errors = [];
  win.webContents.on('console-message', (e) => { if (e.level === 'error') errors.push(e.message); });
  await win.loadFile(path.join(__dirname, '..', 'src', 'renderer', 'index.html'));
  const run = (c) => win.webContents.executeJavaScript(c);
  const wait = (ms) => new Promise((r) => setTimeout(r, ms));
  await run(`(() => { const pe = window.__pe;
    pe.state.orig = ['# A','Eins','Zwei','- x\\n- y'].map(pe.mkCell);
    pe.state.trans = ['# A','Uno','- p\\n- q','Dos'].map(pe.mkCell); pe.render(); })()`);
  const rect = await run(`(() => { const r = document.querySelectorAll('.row')[1].querySelector('.cell.trans').getBoundingClientRect(); return {x: r.left + 40, y: r.top + 10}; })()`);
  win.webContents.sendInputEvent({ type: 'mouseDown', x: Math.round(rect.x), y: Math.round(rect.y), button: 'left', clickCount: 1 });
  win.webContents.sendInputEvent({ type: 'mouseUp', x: Math.round(rect.x), y: Math.round(rect.y), button: 'left', clickCount: 1 });
  await wait(200);
  await win.webContents.insertText('X');
  await wait(100);
  win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Down', modifiers: ['alt'] });
  win.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Down', modifiers: ['alt'] });
  await wait(300);
  const r1 = await run(`({ trans: window.__pe.state.trans.map(c => c.md), editingRow: window.__pe.editing() && window.__pe.editing().i, active: window.__pe.state.active })`);
  await win.webContents.insertText(' Z');
  await wait(100);
  await run(`window.__pe.commitEdit()`);
  const r2 = await run(`window.__pe.state.trans.map(c => c.md)`);
  console.log(JSON.stringify({ r1, r2, errors }, null, 1));
  app.quit();
});
